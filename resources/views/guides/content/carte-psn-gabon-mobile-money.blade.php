    obstacle : le PlayStation Store ne prend pas le Mobile Money. La solution utilisée par les joueurs :
    la <strong>carte PSN</strong>, payée en FCFA par <strong>Airtel Money</strong> ou <strong>Moov Money</strong>,
    qui crédite votre porte-monnaie PlayStation en quelques minutes.
</p>

<h2>Créditer son porte-monnaie PSN depuis le Gabon : les 5 étapes</h2>
<ol class="steps">
    <li><b>Vérifiez la région de votre compte PSN</b> (paramètres du compte). Un compte France utilise des cartes <strong>PSN France</strong> — c'est le point qui évite 90 % des problèmes de code « refusé ».</li>
    <li><b>Choisissez votre carte PSN</b> sur <a href="{{ route('boutique', ['search' => 'PSN']) }}">KardAfrica</a> : 10 €, 20 €, 50 €… la valeur en euros et le prix en FCFA sont affichés sur chaque carte.</li>
    <li><b>Payez par Airtel Money ou Moov Money</b> : validation sur votre téléphone avec votre code secret.</li>
    <li><b>Récupérez le code en ~30 secondes</b> dans « Mes cartes » (espace client).</li>
    <li><b>Utilisez le code</b> : sur console (PlayStation Store → « Utiliser un code ») ou sur <em>store.playstation.com</em>. Le montant est crédité immédiatement sur votre porte-monnaie.</li>
</ol>

<div class="callout info">
    💡 Le porte-monnaie PSN peut cumuler plusieurs cartes : deux cartes de 20 € = 40 € de solde,
    utilisables en une ou plusieurs fois (jeux, abonnements PS Plus, contenus).
</div>

