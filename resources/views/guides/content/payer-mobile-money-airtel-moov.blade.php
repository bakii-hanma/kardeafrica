<p>
    Au Gabon, le <strong>Mobile Money</strong> a remplacé la carte bancaire pour la plupart des paiements —
    y compris sur Internet. Concrètement, payer en ligne par <strong>Airtel Money</strong> ou
    <strong>Moov Money</strong> se déroule toujours de la même façon : vous saisissez votre numéro sur le
    site, puis vous <strong>validez vous-même</strong> la demande de paiement sur votre téléphone. Voici le
    déroulé exact, avec l'exemple d'un achat de carte cadeau sur KardAfrica.
</p>

<h2>Le paiement Mobile Money, étape par étape</h2>
<ol class="steps">
    <li><b>Au moment de payer</b>, choisissez « Airtel Money » ou « Moov Money » et saisissez votre numéro de téléphone.</li>
    <li><b>Une demande de paiement arrive sur votre téléphone</b> (notification ou menu). Elle indique le montant exact et le marchand.</li>
    <li><b>Validez avec votre code secret</b> Mobile Money. Sans cette validation, rien n'est débité — c'est vous qui autorisez chaque paiement.</li>
    <li><b>Le site est notifié automatiquement</b>. Sur KardAfrica, votre code de carte cadeau apparaît en ~30 secondes dans « Mes cartes ».</li>
</ol>

<h2>Est-ce sécurisé ?</h2>
<p>
    Oui, et pour une raison structurelle : votre code secret Mobile Money n'est <strong>jamais saisi sur
    le site</strong> — uniquement sur votre propre téléphone, auprès de votre opérateur. Sur KardAfrica,
    les paiements passent par <strong>E-Billing</strong>, agrégateur de paiement agréé au Gabon.
</p>
<div class="callout">
    ⚠️ Règle d'or : ne communiquez <strong>jamais</strong> votre code secret Mobile Money — ni par
    téléphone, ni par WhatsApp, ni à un « agent ». Aucun marchand légitime ne le demande.
</div>

<h2>Si le paiement échoue</h2>
<p>
    Deux causes dominent : un solde insuffisant, ou une validation expirée (la demande n'a pas été
    confirmée à temps). Dans les deux cas, rien n'est débité — recommencez simplement. Et si un montant
    était débité sans que votre commande soit livrée, le remboursement est automatique ; notre support
    répond sous 24 h pour tout autre cas.
</p>

