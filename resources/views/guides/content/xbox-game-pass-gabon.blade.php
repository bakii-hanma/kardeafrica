<ol class="steps">
    <li><b>Vérifiez la région de votre compte Microsoft</b> (account.microsoft.com) : un compte enregistré en Europe utilise les cartes <strong>EU</strong>.</li>
    <li><b>Choisissez votre formule</b> sur <a href="{{ route('boutique', ['search' => 'Game Pass']) }}">KardAfrica</a> : Essential (console), Premium, ou Ultimate (console + PC + cloud + multijoueur), en 1 à 6 mois.</li>
    <li><b>Payez par Airtel Money ou Moov Money</b> — validation sur votre téléphone, prix final en FCFA affiché avant paiement.</li>
    <li><b>Activez le code</b> sur votre console (Store → « Utiliser un code ») ou sur <em>xbox.com/redeemcode</em>. L'abonnement démarre immédiatement.</li>
</ol>

