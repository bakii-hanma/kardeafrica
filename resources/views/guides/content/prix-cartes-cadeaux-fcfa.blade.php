<h2>Comment le prix en FCFA est-il calculé ?</h2>
<p>
    Le prix FCFA = valeur de la carte convertie au taux du jour, arrondie au palier supérieur.
    C'est pour cela qu'une carte de 10 € ne coûte pas un montant « rond » converti à la calculatrice :
    le taux et les tarifs éditeurs évoluent. La règle KardAfrica est simple : <strong>le prix affiché
    est le prix débité</strong>, que vous payiez par Airtel Money, Moov Money ou carte bancaire.
</p>

