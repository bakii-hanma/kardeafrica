<p>
    « Comment payer <strong>Spotify</strong> au Gabon sans carte bancaire ? » — c'est l'une des
    questions les plus posées. La réponse générale vaut pour tout le streaming musical :
    l'abonnement se paie par <strong>carte cadeau</strong>, achetée en FCFA par
    <strong>Airtel Money</strong> ou <strong>Moov Money</strong>. Voici où en est chaque service,
    honnêtement.
</p>

<h2>Spotify : le principe (et la disponibilité)</h2>
<p>
    Spotify Premium s'active par carte cadeau Spotify sur <em>spotify.com/redeem</em> — le compte
    est crédité et l'abonnement s'y prélève, sans carte bancaire. <strong>Ces cartes ne sont pas
    disponibles sur KardAfrica pour le moment</strong> : dès qu'elles rejoindront le catalogue,
    elles apparaîtront sur la <a href="{{ route('boutique') }}">boutique</a> et dans le tableau
    de cette page.
</p>

<h2>Deezer : disponible immédiatement, en FCFA</h2>
<p>
    L'alternative n°1, <strong>disponible dès maintenant</strong> : <strong>Deezer</strong>
    (Premium ou Family, de 1 à 12 mois). Même principe, même simplicité :
</p>
<ol class="steps">
    <li><b>Choisissez votre carte Deezer</b> sur <a href="{{ route('boutique', ['search' => 'Deezer']) }}">KardAfrica</a> — Premium (1 compte) ou Family (jusqu'à 6 profils).</li>
    <li><b>Payez par Airtel Money ou Moov Money</b> — le prix FCFA affiché est le prix final.</li>
    <li><b>Recevez le code en ~30 secondes</b> dans votre espace client « Mes cartes ».</li>
    <li><b>Activez-le sur <em>deezer.com/gift</em></b>, connecté à votre compte : l'abonnement démarre immédiatement.</li>
</ol>

