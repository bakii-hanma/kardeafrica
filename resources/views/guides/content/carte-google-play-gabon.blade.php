<p>
    Applications payantes, <strong>diamants Free Fire</strong>, UC PUBG Mobile, abonnements…
    tout ce qui se paie sur le Play Store passe par un moyen de paiement Google — que la
    plupart des joueurs gabonais n'ont pas. La <strong>carte Google Play</strong> règle le
    problème : payée en FCFA par <strong>Airtel Money</strong> ou <strong>Moov Money</strong>,
    elle crédite votre solde Google Play, qui paie ensuite tous vos achats.
</p>

<h2>Créditer son compte Google Play : les 4 étapes</h2>
<ol class="steps">
    <li><b>Vérifiez le pays de votre profil Google Play</b> (Play Store → Paramètres → Général) : le code doit correspondre au pays du compte.</li>
    <li><b>Choisissez votre carte</b> sur <a href="{{ route('boutique', ['search' => 'Google Play']) }}">KardAfrica</a> — la valeur (ex. 35 €) et le prix en FCFA sont affichés côte à côte.</li>
    <li><b>Payez par Airtel Money ou Moov Money</b> et recevez le code en ~30 secondes dans « Mes cartes ».</li>
    <li><b>Utilisez le code</b> : app Play Store → menu profil → <em>Paiements et abonnements</em> → <em>Utiliser un code</em> (ou <em>play.google.com/redeem</em>). Le montant est ajouté à votre solde.</li>
</ol>

<div class="callout">
    ⚠️ <strong>Le pays du compte est la règle n°1.</strong> Un code d'une région différente de celle
    de votre profil de paiement Google sera refusé. Vérifiez avant d'acheter.
</div>

<h2>Free Fire, PUBG : comment payer avec le solde Google Play ?</h2>
<p>
    Une fois le solde crédité, ouvrez le jeu et effectuez l'achat intégré normalement :
    Google Play propose votre solde comme moyen de paiement. Aucune carte bancaire,
    aucun compte étranger — le solde couvre diamants, passes et packs.
</p>

