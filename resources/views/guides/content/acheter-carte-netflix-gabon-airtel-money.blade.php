<p>
    Pas de carte bancaire internationale ? C'est le cas de la majorité des abonnés au Gabon — et c'est
    exactement le problème que résout la <strong>carte cadeau Netflix</strong> : vous payez en FCFA par
    <strong>Airtel Money</strong> ou <strong>Moov Money</strong>, vous recevez un code, et ce code crédite
    votre compte Netflix. Voici la méthode complète, étape par étape.
</p>

<h2>Payer Netflix par Airtel Money : les 5 étapes</h2>
<ol class="steps">
    <li><b>Choisissez votre carte Netflix</b> sur <a href="{{ route('boutique', ['search' => 'Netflix']) }}">KardAfrica</a> : sélectionnez le montant (la valeur en euros et le prix en FCFA sont affichés côte à côte).</li>
    <li><b>Ajoutez au panier et validez</b> — le prix affiché en FCFA est le prix final, sans frais cachés.</li>
    <li><b>Payez par Airtel Money ou Moov Money</b> : saisissez votre numéro, puis validez la demande de paiement reçue sur votre téléphone avec votre code secret.</li>
    <li><b>Recevez votre code en ~30 secondes</b> dans votre espace client, rubrique « Mes cartes ».</li>
    <li><b>Créditez votre compte Netflix</b> : rendez-vous sur <em>netflix.com/redeem</em>, connectez-vous et saisissez le code. Le montant est ajouté à votre solde, qui paie ensuite votre abonnement mois après mois.</li>
</ol>

<div class="callout">
    ⚠️ <strong>La règle n°1 : la région.</strong> Une carte Netflix est liée à une région (ex. Europe/France)
    et fonctionne sur les comptes Netflix de cette région — elle est indiquée sur chaque carte
    (drapeau + devise). Vérifiez la région de votre compte avant d'acheter.
</div>

